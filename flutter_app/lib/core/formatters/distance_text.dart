/// 距离文案。
///
/// 一公里以内报米（「420 米」），超过一公里报一位小数的公里（「1.2 公里」）。
/// 反过来把 420 米写成「0.4 公里」，人会失去尺度感 —— 而"附近"这个功能
/// 全靠尺度感才说得通。
///
/// 负数和异常值一律按 0 处理：距离来自服务端，但界面上出现「-3 米」
/// 比显示「0 米」要难解释得多。
String distanceText(int meters) {
  final int safe = meters < 0 ? 0 : meters;
  if (safe < 1000) {
    return '$safe 米';
  }
  // 整公里不写小数点：「3 公里内找到 2 个景点」比「3.0 公里内」干净，
  // 而且这里报的是半径，本来就是一个约数。
  if (safe % 1000 == 0) {
    return '${safe ~/ 1000} 公里';
  }
  return '${(safe / 1000).toStringAsFixed(1)} 公里';
}
